const dictionaries: Record<Locale, Record<CopyKey, string>> = { ar, fr, en };

export function useI18n(): {
    locale: Locale;
    dir: 'rtl' | 'ltr';
    t: (key: CopyKey) => string;
} {
    const { locale } = usePage().props;
    const current: Locale = locale === 'fr' || locale === 'en' ? locale : 'ar';

    return {
        locale: current,
        dir: current === 'ar' ? 'rtl' : 'ltr',
        t: (key) => dictionaries[current][key],
    };
}
